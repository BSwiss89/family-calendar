test('timed accepted shares appear on Schedule hours, while only untimed shares stay in All Day', () => {
  assert.match(app, /includeReceivedShares = false/)
  assert.match(app, /if \(includeReceivedShares\)/)
  assert.match(app, /for \(const sharedEvent of sharedEventsInRange\(/)
  assert.match(app, /if \(sharedEvent\.time === null\) continue/)
  assert.match(app, /calendarEvent: null, sharedEvent, dateKey, visibleStart, visibleEnd/)
  assert.match(app, /durationMinutes: visibleEnd - visibleStart/)
  assert.match(app, /endMinutes \+= 1440/)
  assert.match(app, /getScheduleTimedEventLayouts\(\s*targetDate, true\s*\)/)
  assert.match(app, /getScheduleTimedEventLayouts\(\s*scheduleDay, true\s*\)/)
  assert.equal((app.match(/filter\(shared => shared\.time === null\)/g) ?? []).length, 2)
  assert.match(app, /some\(shared => shared\.time === null\)/)
  assert.match(app, /shared-schedule-timed-event/)
  assert.match(app, /setSelectedReceivedEvent\(timedEventLayout\.sharedEvent\)/)
  assert.match(app, /setSelectedReceivedEvent\(sharedEvent\)/)
  assert.match(app, /Shared by \{timedEventLayout\.sharedEvent\.sharedBy\}/)
  // Read-only snapshot stays separate from locally editable CalendarEvent.
  assert.match(app, /else openEventDetails\(timedEventLayout\.calendarEvent!, timedEventLayout\.dateKey\)/)
  const css = fs.readFileSync(path.join(root, 'src/SharedEventsOverlay.css'), 'utf8')
  assert.match(css, /\.schedule-event\.shared-schedule-timed-event/)
  assert.match(css, /\.mobile-schedule-event\.shared-schedule-timed-event/)
})

